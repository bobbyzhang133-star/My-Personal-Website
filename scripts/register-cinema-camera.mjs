import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const sharp = createRequire(import.meta.url)('sharp');
const evidence = new URL('../artifacts/films-camera/', import.meta.url);
const assets = new URL('../public/portfolio/assets/room/cinema-camera/', import.meta.url);
const origin = [1227, 276];
const render = await readFile(new URL('camera-rest.png', evidence));
const { data, info: { width, height } } = await sharp(render).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const opaque = (x, y) => x >= 0 && x < width && y >= 0 && y < height && data[(y * width + x) * 4 + 3] >= 128;
const edges = new Map();
function addEdge(x, y, nextX, nextY) {
  const key = y * (width + 1) + x;
  const next = nextY * (width + 1) + nextX;
  edges.set(key, [...(edges.get(key) ?? []), next]);
}
for (let y = 0; y < height; y++) {
  for (let x = 0; x < width; x++) {
    if (!opaque(x, y)) continue;
    if (!opaque(x, y - 1)) addEdge(x, y, x + 1, y);
    if (!opaque(x + 1, y)) addEdge(x + 1, y, x + 1, y + 1);
    if (!opaque(x, y + 1)) addEdge(x + 1, y + 1, x, y + 1);
    if (!opaque(x - 1, y)) addEdge(x, y + 1, x, y);
  }
}
const loops = [];
while (edges.size) {
  const start = edges.keys().next().value;
  let cursor = start;
  const loop = [];
  do {
    loop.push([cursor % (width + 1), Math.floor(cursor / (width + 1))]);
    const outgoing = edges.get(cursor);
    if (!outgoing?.length) throw new Error('Open camera contour');
    const next = outgoing.pop();
    if (!outgoing.length) edges.delete(cursor);
    cursor = next;
  } while (cursor !== start);
  loops.push(loop);
}
const contour = loops.reduce((outer, loop) => loop.length > outer.length ? loop : outer, []);
const corners = contour.filter(([x, y], index) => {
  const [beforeX, beforeY] = contour.at(index - 1);
  const [afterX, afterY] = contour[(index + 1) % contour.length];
  return (x - beforeX) * (afterY - y) !== (y - beforeY) * (afterX - x);
});
const path = corners.map(([x, y], index) => `${index ? 'L' : 'M'}${x + origin[0]} ${y + origin[1]}`).join('') + 'Z';
const projection = JSON.parse(await readFile(new URL('projection.json', evidence), 'utf8'));
const contacts = projection.contacts.map(([x, y]) => [
  Number((x + origin[0]).toFixed(2)), Number((y + origin[1]).toFixed(2)),
]);
await sharp(render).webp({ lossless: true }).toFile(fileURLToPath(new URL('studio-65.webp', assets)));
await writeFile(new URL('studio-65.png', assets), render);
await writeFile(new URL('../public/portfolio/assets/js/scenes/cinema-camera-registration.js', import.meta.url),
  `// Generated by scripts/register-cinema-camera.mjs from the Blender rest projection.\nexport const CINEMA_CAMERA = Object.freeze(${JSON.stringify({ box: [...origin, width, height], support: 'desk', contacts, path }, null, 2)});\n`);
