import { readFile, mkdir, writeFile, copyFile } from 'node:fs/promises';
import path from 'node:path';
import ts from 'typescript';

const source = process.argv[2];
if (!source || !path.isAbsolute(source)) throw new Error('An absolute extracted npm package path is required.');
const manifest = JSON.parse(await readFile(path.join(source, 'package.json'), 'utf8'));
if (manifest.name !== 'page-flip' || manifest.version !== '2.0.7') throw new Error('Expected page-flip 2.0.7.');
const parts = await Promise.all(['src/Helper.ts', 'src/Flip/FlipCalculation.ts'].map(file => readFile(path.join(source, file), 'utf8')));
const input = `const FlipDirection = { FORWARD: 0, BACK: 1 };\nconst FlipCorner = { TOP: 'top', BOTTOM: 'bottom' };\n` + parts.map(text => text.replace(/^import .*;\r?\n/gm, '')).join('\n');
const output = ts.transpileModule(input, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, removeComments: false } }).outputText;
const destination = new URL('../public/portfolio/assets/js/vendor/', import.meta.url);
await mkdir(destination, { recursive: true });
await writeFile(new URL('st-page-flip-geometry.js', destination), `/* StPageFlip/page-flip 2.0.7 geometry subset. Copyright (c) 2020 Nodlik.\n * MIT; see st-page-flip-LICENSE.txt. Generated by scripts/vendor-page-fold.mjs.\n * Type erasure, standalone enums, fractional sizing and an unused catch binding differ. */\n` + output.replace(/parseInt\((pageWidth|pageHeight), 10\)/g, 'parseFloat($1)').replace(/catch \(e\)/g, 'catch'));
await copyFile(path.join(source, 'LICENSE'), new URL('st-page-flip-LICENSE.txt', destination));
