"""Copy unchanged Unity sprite atlases and translate native swim/boss timing.
No source code is executed and the drive is read-only. Requires bundled Pillow.
"""
import json
import re
import shutil
from pathlib import Path
from PIL import Image

ROOT = Path('/Volumes/adol U300/CMU/nhsga/Lightning_Round/NHSGA_Asteroids/LR_asteroids/Assets')
REPO = Path(__file__).resolve().parents[1]
DEST = REPO / 'public/portfolio/assets/game-source/ocean-animals'
CLIPS = {
    'swordfish': 'Lvl 1 Swordfish Movement/Swordfish_Movement.anim',
    'swordfish-green': 'Lvl 1 Swordfish Movement/Swordfish_Move2.anim',
    'grouper': 'Level 2/Lvl 2 Grouper Move/angelaw2_Level2_GrouperMove.anim',
    'parrotfish': 'Level 2/Lvl 2 Parrotfish Move/angelaw2_Level2_ParrotfishMove.anim',
    'manta': 'Level 2/Manta Ray/angelaw2_Lvl2_MantarayMove.anim',
    'eel': 'Lvl 3 ElectricEel/Eel_Move.anim',
    'angler': 'Lvl 3 Angler Move/Assembly-CSharp.csproj.anim',
    'squid': 'Lvl3 Squid Enemy Animations/Squid Enemy Move Anim.anim',
    'boss': 'Lvl3 Boss/BossAnimation.anim',
}


def run():
    DEST.mkdir(parents=True, exist_ok=True)
    textures = {}
    for meta in ROOT.rglob('*.meta'):
        source = Path(str(meta)[:-5])
        if source.suffix.lower() != '.png':
            continue
        text = meta.read_text()
        match = re.search(r'^guid: (\w+)', text, re.M)
        if match:
            textures[match[1]] = (source, text)
    copied, output = {}, {}
    for name, clip_path in CLIPS.items():
        clip = ROOT / 'Animations' / clip_path
        text = clip.read_text()
        curve = text.split('  m_PPtrCurves:')[1].split('    attribute:')[0]
        keys = re.findall(r'- time: ([\d.]+)\s+value: \{fileID: (-?\d+), guid: (\w+)', curve)
        frames, bounds = [], []
        for time, sprite_id, guid in keys:
            source, meta = textures[guid]
            image = Image.open(source).convert('RGBA')
            rects = {}
            for block in meta.split('    - serializedVersion: 2')[1:]:
                match = re.search(r'\brect:.*?x: ([\d.]+)\s+y: ([\d.]+)\s+width: ([\d.]+)\s+height: ([\d.]+).*?internalID: (-?\d+)', block, re.S)
                if match:
                    x, y, w, h = map(lambda value:int(float(value)), match.groups()[:4])
                    rects[match[5]] = [x, image.height-y-h, w, h]
            rect = rects.get(sprite_id, [0, 0, image.width, image.height])
            if guid not in copied:
                filename = name+'-'+str(len(copied))+source.suffix.lower()
                shutil.copyfile(source, DEST / filename)
                copied[guid] = '/assets/game-source/ocean-animals/'+filename
            x, y, w, h = rect
            box = image.getchannel('A').crop((x,y,x+w,y+h)).getbbox()
            assert box
            frames.append({'time':float(time), 'src':copied[guid], 'rect':rect, 'trim':[box[0],box[1],box[2]-box[0],box[3]-box[1]]})
            bounds.append(box)
        assert frames, name
        crop = [0,0,max(frame['rect'][2] for frame in frames),max(frame['rect'][3] for frame in frames)]
        for frame in frames:
            frame['logicalSize']=crop[2:]
            frame['offset']=[(crop[2]-frame['rect'][2])/2+frame['trim'][0],(crop[3]-frame['rect'][3])/2+frame['trim'][1]]
        duration = float(re.search(r'm_StopTime: ([\d.]+)',text)[1])
        output[name] = {'crop':crop, 'facing':-1, 'preview':'move', 'clips':{'idle':{'duration':duration,'loop':True,'frames':frames}, 'move':{'duration':duration,'loop':True,'frames':frames}}, 'source':str(clip.relative_to(ROOT))}
    for name in ['TentacleLeft.png','TentacleRight.png']:
        shutil.copyfile(ROOT/'Sprites/Boss Tentacles'/name,DEST/name)
    (REPO/'public/portfolio/assets/js/ocean-animal-data.js').write_text('// Native Unity pixels/timing; generated by scripts/import-ocean-animals.py.\nexport const OCEAN_ANIMALS = '+json.dumps(output,indent=2)+';\n')
    print({key:{'crop':value['crop'],'frames':len(value['clips']['move']['frames'])} for key,value in output.items()})


if __name__=='__main__':
    run()
