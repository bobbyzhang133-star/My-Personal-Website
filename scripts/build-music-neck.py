"""Build the Room guitar's neck close-up in an isolated Blender scene."""
import json
from pathlib import Path

import bpy

root = Path(__file__).resolve().parents[1]
assets = root / "public/portfolio/assets/room/guitar-neck"
previous = bpy.context.window.scene
scene = bpy.data.scenes.new("Room Guitar Neck")
bpy.context.window.scene = scene
scale = .648
fret = lambda n: scale * (1 - 2 ** (-n / 12))
span = fret(9) + .010
height = 480
width = 168
ortho = span * 1.10

def material(name, rgb):
    m = bpy.data.materials.new(name)
    m.diffuse_color = (*rgb, 1)
    m.use_nodes = True
    shader = next(node for node in m.node_tree.nodes if node.type == "BSDF_PRINCIPLED")
    shader.inputs["Base Color"].default_value = m.diffuse_color
    return m

wood = material("Rosewood fretboard", (.109, .043, .026))
cream = material("Ivory binding and nut", (.78, .61, .37))
metal = material("Nickel fret wire", (.55, .49, .39))
red = material("Wine red lacquer", (.34, .036, .047))

def block(name, xyz, dimensions, mat):
    bpy.ops.mesh.primitive_cube_add(size=1, location=xyz)
    obj = bpy.context.object
    obj.name = name
    obj.dimensions = dimensions
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    obj.data.materials.append(mat)
    return obj

def neck_width(y):
    return .044 + .012 * y / span

def taper(name, margin, z, thickness, mat):
    vertices = [(sign * (neck_width(y)/2 + margin), -y, level)
                for level in [z-thickness, z] for y in [0,span] for sign in [-1,1]]
    faces = [(0,1,3,2),(4,6,7,5),(0,4,5,1),(2,3,7,6),(0,2,6,4),(1,5,7,3)]
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(vertices, [], faces)
    obj = bpy.data.objects.new(name, mesh)
    scene.collection.objects.link(obj)
    mesh.materials.append(mat)

taper("Lacquered neck", .003, .005, .021, red)
taper("Cream binding", .0015, .007, .002, cream)
taper("Tapered rosewood board", 0, .008, .002, wood)
for n in range(10):
    y = fret(n)
    block("Nut" if n == 0 else f"Fret {n}", (0,-y,.009),
          (neck_width(y), .003 if n == 0 else .0014,.002), cream if n == 0 else metal)
for n in [3,5,7,9]:
    y = (fret(n-1) + fret(n))/2
    bpy.ops.mesh.primitive_cylinder_add(vertices=16, radius=.0025, depth=.0008, location=(0,-y,.0085))
    bpy.context.object.name = f"Inlay {n}"
    bpy.context.object.data.materials.append(cream)
for i in range(6):
    x = (i-2.5)*.007
    block(f"String {i+1}", (x,-span/2,.011), (.00045+i*.000065,span,.00065), metal)

camera = bpy.data.objects.new("Aligned neck view", bpy.data.cameras.new("Aligned neck view"))
scene.collection.objects.link(camera)
camera.location = (0,-span/2,1)
camera.data.type = "ORTHO"
camera.data.ortho_scale = ortho
scene.camera = camera
scene.render.resolution_x = width
scene.render.resolution_y = height
scene.render.resolution_percentage = 100
scene.render.engine = "BLENDER_WORKBENCH"
scene.display.shading.color_type = "MATERIAL"
scene.display.shading.show_cavity = True
scene.view_settings.view_transform = "Standard"
scene.render.film_transparent = True
scene.render.image_settings.file_format = "WEBP"
scene.render.image_settings.color_mode = "RGBA"
scene.render.filepath = str(assets / "fretboard.webp")
bpy.ops.render.render(scene=scene.name, write_still=True)
bpy.ops.object.select_all(action="DESELECT")
for obj in scene.objects:
    if obj.type == "MESH":
        obj.select_set(True)
bpy.ops.export_scene.gltf(filepath=str(assets/"fretboard.glb"), export_format="GLB", use_selection=True)
anchors = [{"fret":n, "x":50, "y":round(50 + ((fret(n-1)+fret(n))/2-span/2)/ortho*100,3)} for n in [3,7]]
(assets/"provenance.json").write_text(json.dumps({"source":"scripts/build-music-neck.py","scaleMeters":scale,"fretCount":9,"anchors":anchors,"reference":"Existing wine-red Room guitar; straight-on close-up of its neck."},indent=2)+"\n")
(root/"public/portfolio/assets/js/scenes/music-neck-anchors.js").write_text(
    "// Generated by scripts/build-music-neck.py.\nexport const MUSIC_FRET_ANCHORS = "
    + json.dumps(anchors, indent=2) + ";\n")
bpy.context.window.scene = previous
print("FRET ANCHORS", anchors)
